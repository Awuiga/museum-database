"""Экспонаты музея — вторая таблица варианта 14 (замена phones)."""

from psycopg2 import sql
from psycopg2.extras import RealDictCursor

from dbtable import DbTable


class ExhibitsTable(DbTable):
    name = "exhibits"

    def primary_key(self):
        return "exhibit_id"

    def columns(self):
        return [
            "collection_id", "name", "short_description", "insurance_value_rub",
            "creation_century", "hall_name", "height_cm", "width_cm", "length_cm",
            "temperature_control_required", "humidity_control_required",
            "protected_from_visitors",
        ]

    def create(self, cursor):
        cursor.execute(sql.SQL("""
            CREATE TABLE IF NOT EXISTS {} (
                exhibit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                collection_id BIGINT NOT NULL REFERENCES {} (collection_id)
                    ON DELETE CASCADE,
                name VARCHAR(200) NOT NULL,
                short_description TEXT NOT NULL DEFAULT '',
                insurance_value_rub NUMERIC(14,2) NOT NULL DEFAULT 0,
                creation_century SMALLINT NOT NULL,
                hall_name VARCHAR(200) NOT NULL,
                height_cm NUMERIC(10,2) NOT NULL,
                width_cm NUMERIC(10,2) NOT NULL,
                length_cm NUMERIC(10,2) NOT NULL,
                temperature_control_required BOOLEAN NOT NULL DEFAULT FALSE,
                humidity_control_required BOOLEAN NOT NULL DEFAULT FALSE,
                protected_from_visitors BOOLEAN NOT NULL DEFAULT FALSE,
                CONSTRAINT chk_exhibit_name_not_empty CHECK (length(btrim(name)) > 0),
                CONSTRAINT chk_exhibit_hall_not_empty CHECK (length(btrim(hall_name)) > 0),
                CONSTRAINT chk_insurance_nonnegative CHECK (insurance_value_rub >= 0),
                CONSTRAINT chk_century_not_zero CHECK (creation_century <> 0),
                CONSTRAINT chk_dimensions_positive CHECK (
                    height_cm > 0 AND width_cm > 0 AND length_cm > 0
                )
            )
        """).format(self.table_sql, self.dbconn.identifier("museum_collections")))
        cursor.execute(sql.SQL("CREATE INDEX IF NOT EXISTS {} ON {} (collection_id)").format(
            sql.Identifier("ix_exhibits_collection_id"), self.table_sql
        ))

    def count_by_collection(self, collection_id):
        query = sql.SQL("SELECT count(*) FROM {} WHERE collection_id = %s").format(self.table_sql)
        with self.dbconn.conn:
            with self.dbconn.conn.cursor() as cursor:
                cursor.execute(query, (collection_id,))
                return cursor.fetchone()[0]

    def all_by_collection(self, collection_id, limit=8, offset=0):
        if not (1 <= limit <= 100) or offset < 0:
            raise ValueError("Некорректные параметры страницы.")
        query = sql.SQL("""
            SELECT * FROM {} WHERE collection_id = %s
            ORDER BY lower(name), exhibit_id LIMIT %s OFFSET %s
        """).format(self.table_sql)
        with self.dbconn.conn:
            with self.dbconn.conn.cursor(cursor_factory=RealDictCursor) as cursor:
                cursor.execute(query, (collection_id, limit, offset))
                return list(cursor.fetchall())

    def update_by_collection(self, exhibit_id, collection_id, record):
        # update второй таблицы остаётся внутри выбранной коллекции.
        cols = [col for col in self.columns() if col != "collection_id"]
        assignments = sql.SQL(", ").join(
            sql.SQL("{} = %s").format(sql.Identifier(col)) for col in cols
        )
        query = sql.SQL("UPDATE {} SET {} WHERE exhibit_id = %s AND collection_id = %s").format(
            self.table_sql, assignments
        )
        with self.dbconn.conn:
            with self.dbconn.conn.cursor() as cursor:
                cursor.execute(query, tuple(record[col] for col in cols) + (exhibit_id, collection_id))
                return cursor.rowcount

    def delete_by_collection(self, exhibit_id, collection_id):
        query = sql.SQL("DELETE FROM {} WHERE exhibit_id = %s AND collection_id = %s").format(self.table_sql)
        with self.dbconn.conn:
            with self.dbconn.conn.cursor() as cursor:
                cursor.execute(query, (exhibit_id, collection_id))
                return cursor.rowcount
