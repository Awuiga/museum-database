"""Коллекции музея — первая таблица варианта 14 (замена people)."""

from psycopg2 import sql

from dbtable import DbTable


class CollectionsTable(DbTable):
    name = "museum_collections"

    def primary_key(self):
        return "collection_id"

    def columns(self):
        return ["name", "short_description", "display_start_date", "display_end_date"]

    def create(self, cursor):
        cursor.execute(sql.SQL("""
            CREATE TABLE IF NOT EXISTS {} (
                collection_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR(200) NOT NULL,
                short_description TEXT NOT NULL DEFAULT '',
                display_start_date DATE NOT NULL,
                display_end_date DATE NOT NULL,
                CONSTRAINT chk_collection_name_not_empty CHECK (length(btrim(name)) > 0),
                CONSTRAINT chk_collection_date_order CHECK (display_end_date >= display_start_date)
            )
        """).format(self.table_sql))

    def delete_with_exhibits(self, collection_id):
        """ON DELETE CASCADE удаляет связанные экспонаты в той же транзакции."""
        return self.delete_one(collection_id)
